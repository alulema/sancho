"""Generates the Mosquitto configuration for an environment from contracts/acl.py.

Writes into the output directory:
    mosquitto.conf   listeners and limits
    acl              per-role permissions
    passwd           salted PBKDF2-SHA512 hashes (Mosquitto `$7$` format)
    credentials/     one plain-text password file per role, for the components

Existing passwords are kept unless --rotate is given. The output directory holds
secrets: keep it out of git (`secrets/` is ignored) and readable only by its owner.

Usage:
    python -m deploy.broker.broker_config --env test --out secrets/mqtt/test \
        --listen 127.0.0.1:1883
"""

import argparse
import base64
import hashlib
import os
import secrets
from pathlib import Path

from contracts.acl import roles_for
from contracts.bus import MAX_PACKET_BYTES

# Same broker on the Nano and in tests: eclipse-mosquitto 2.1.2-alpine (multi-arch index).
MOSQUITTO_IMAGE = (
    "eclipse-mosquitto@sha256:75d6662dee52c947dc9dd9c29f1d8d7ffef78ddaf38001caa09755681e8bbc98"
)
BROKER_DIR_IN_IMAGE = "/mosquitto/config"
ITERATIONS = 101  # Mosquitto's default for `$7$`


def hash_password(password: str, *, salt: bytes | None = None) -> str:
    salt = salt or os.urandom(12)
    digest = hashlib.pbkdf2_hmac("sha512", password.encode(), salt, ITERATIONS)
    return f"$7${ITERATIONS}${base64.b64encode(salt).decode()}${base64.b64encode(digest).decode()}"


def acl_text(environment: str) -> str:
    lines = [f"# Generated from contracts/acl.py for '{environment}'. Do not edit."]
    for role in roles_for(environment):
        lines += ["", f"user {role.name}"]
        lines += [f"topic write {pattern}" for pattern in role.publish]
        lines += [f"topic read {pattern}" for pattern in role.subscribe]
    return "\n".join(lines) + "\n"


def conf_text(listeners: list[str], broker_dir: str) -> str:
    lines = [
        "# Generated by deploy/broker/broker_config.py. Do not edit.",
        "allow_anonymous false",
        f"password_file {broker_dir}/passwd",
        f"acl_file {broker_dir}/acl",
        "persistence false",
        f"max_packet_size {MAX_PACKET_BYTES}",
        "log_dest stdout",
        "log_type error",
        "log_type warning",
        "log_type notice",
        "connection_messages true",
    ]
    for spec in listeners:
        address, port = spec.rsplit(":", 1)
        if address.startswith("@"):
            lines += ["", f"listener {int(port)}", f"bind_interface {address[1:]}"]
        else:
            lines += ["", f"listener {int(port)} {address}"]
    return "\n".join(lines) + "\n"


def _write_private(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(path, 0o600)


def generate(
    out: Path,
    environment: str,
    listeners: list[str],
    *,
    broker_dir: str | None = None,
    rotate: bool = False,
) -> dict[str, str]:
    """Writes the configuration and returns the password of each role."""
    if not listeners:
        raise ValueError("at least one listener is needed")
    out.mkdir(parents=True, exist_ok=True)
    os.chmod(out, 0o700)
    roles = [role.name for role in roles_for(environment)]
    credentials = out / "credentials"
    credentials.mkdir(exist_ok=True)
    os.chmod(credentials, 0o700)
    passwords = {}
    for name in roles:
        path = credentials / name
        if path.exists() and not rotate:
            passwords[name] = path.read_text().strip()
        else:
            passwords[name] = secrets.token_urlsafe(32)
            _write_private(path, passwords[name] + "\n")
    # Roles of other environments must not keep working credentials here.
    if credentials.exists():
        for stale in credentials.iterdir():
            if stale.name not in roles:
                stale.unlink()
    _write_private(
        out / "passwd", "".join(f"{n}:{hash_password(p)}\n" for n, p in passwords.items())
    )
    _write_private(out / "acl", acl_text(environment))
    _write_private(out / "mosquitto.conf", conf_text(listeners, broker_dir or str(out.resolve())))
    return passwords


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--env", required=True, choices=["prod", "test"])
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument(
        "--listen",
        action="append",
        required=True,
        help="ADDRESS:PORT, or @INTERFACE:PORT to bind to a network interface",
    )
    parser.add_argument("--broker-dir", help="where the broker sees --out (e.g. in a container)")
    parser.add_argument("--rotate", action="store_true", help="generate new passwords")
    args = parser.parse_args()
    generate(args.out, args.env, args.listen, broker_dir=args.broker_dir, rotate=args.rotate)
    print(f"configuration for '{args.env}' written to {args.out}")


if __name__ == "__main__":
    main()
